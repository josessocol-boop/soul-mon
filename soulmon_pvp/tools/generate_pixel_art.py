"""Generates ALL pixel-art assets for Soul-Mon PvP (needs Pillow):
   - 8 character sheets (64px frames: idle4 run6 jump2 dash2 attack4 hitstun2 ko3; drawn at 32px, 2x nearest)
   - per-move effect strips, projectiles, traps, status icons, arena tiles/background
   - fx_table.gd (maps fighter id + move key -> art) so roster scripts need no edits.
Run from the project root:  python3 tools/generate_pixel_art.py
Reference art lives in assets/references (used for palette/silhouette guidance only)."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pixel_core import make_sheet
from pixel_characters import ROSTER
from pixel_effects import *

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
A = os.path.join(ROOT, "assets")
FX = os.path.join(A, "fx")
os.makedirs(FX, exist_ok=True)

# (fighter, move) -> (shape, w, h, palette, kwargs)   sizes are ~half the hitbox (art is shown ~2x)
MELEE = {
    ("marshadow", "basic"): ("burst", 22, 16, "shadow", {}),
    ("marshadow", "special1"): ("streak", 32, 22, "shadow", {}),
    ("marshadow", "special2"): ("streak", 34, 26, "venom", {}),
    ("marshadow", "ultimate"): ("flurry", 76, 46, "shadow", {}),
    ("gholdengo", "basic"): ("slash", 46, 22, "gold", {}),
    ("gholdengo", "special2"): ("burst", 104, 74, "gold", {}),
    ("tinkaton", "basic"): ("slash", 58, 38, "pink", {}),
    ("tinkaton", "special1"): ("column", 46, 66, "pink", {"down": True}),
    ("tinkaton", "special2"): ("spin", 104, 36, "pink", {}),
    ("tinkaton", "ultimate"): ("burst", 120, 76, "pink", {}),
    ("greninja", "basic"): ("slash", 32, 14, "water", {}),
    ("greninja", "ultimate"): ("beam", 220, 28, "water", {}),
    ("scizor", "basic"): ("slash", 34, 20, "steel", {}),
    ("scizor", "special1"): ("flurry", 26, 18, "steel", {}),
    ("scizor", "special2"): ("xslash", 56, 46, "crimson", {}),
    ("scizor", "ultimate"): ("streak", 76, 50, "crimson", {}),
    ("decidueye", "basic"): ("slash", 24, 16, "leaf", {}),
    ("blaziken", "basic"): ("burst", 28, 18, "fire", {}),
    ("blaziken", "special1"): ("column", 32, 70, "fire", {}),
    ("blaziken", "special2"): ("column", 28, 36, "fire", {"down": True}),
    ("blaziken", "ultimate"): ("streak", 60, 48, "fire", {}),
    ("gengar", "basic"): ("slash", 26, 18, "venom", {}),
}
PROJ = {   # name: (strip, frames, display scale, fps)
    "proj_coin": (coin_strip(), 4, 2.0, 14.0),
    "proj_shuriken": (shuriken_strip(), 2, 2.0, 14.0),
    "proj_wave": (wave_strip(), 3, 2.0, 10.0),
    "proj_arrow": (arrow_strip(), 2, 2.0, 12.0),
    "proj_orb": (orb_strip("venom"), 4, 2.0, 10.0),
}
TABLE = {   # fighter -> move -> projectile / trap art
    "gholdengo": {"special1": "proj_coin", "ultimate": "proj_coin"},
    "greninja": {"special1": "proj_shuriken", "special2": "proj_wave"},
    "decidueye": {"special1": "proj_arrow", "ultimate": "proj_arrow"},
    "gengar": {"special1": "proj_orb", "ultimate": ("proj_orb", 4.2)},
}
TRAPS = {"decidueye": ("trap_leaf", trap_strip("leaf")), "gengar": ("trap_poison", trap_strip("poison"))}

def main():
    for fid, fn in ROSTER.items():
        make_sheet(fn, os.path.join(A, fid + "_sheet.png"))
    table = {}
    for (fid, mv), (shape, w, h, pal, kw) in MELEE.items():
        name = "%s_%s.png" % (fid, mv)
        strip(shape, w, h, PAL[pal], 4, **kw).save(os.path.join(FX, name))
        table.setdefault(fid, {})[mv] = '{"fx": "res://assets/fx/%s", "fx_frames": 4}' % name
    for name, (img, frames, scale, fps) in PROJ.items():
        img.save(os.path.join(FX, name + ".png"))
    for fid, moves in TABLE.items():
        for mv, ref in moves.items():
            name, scale = (ref, PROJ[ref][2]) if isinstance(ref, str) else (ref[0], ref[1])
            _, frames, _, fps = PROJ[name]
            table.setdefault(fid, {})[mv] = ('{"proj_tex": "res://assets/fx/%s.png", "proj_frames": %d, "proj_scale": %.1f, '
                                             '"proj_fps": %.1f, "proj_spin": 0.0}') % (name, frames, scale, fps)
    for fid, (name, img) in TRAPS.items():
        img.save(os.path.join(FX, name + ".png"))
        table.setdefault(fid, {})["special2"] = ('{"trap_tex": "res://assets/fx/%s.png", "trap_frames": 4, "trap_scale": 2.0, '
                                                 '"trap_fps": 8.0}') % name
    for n in ("burn", "slow", "poison"):
        icon(n).save(os.path.join(A, "icon_%s.png" % n))
    background().save(os.path.join(A, "background.png"))
    stone_tile().save(os.path.join(A, "stone_tile.png"))
    grass_top().save(os.path.join(A, "grass_top.png"))

    lines = ["class_name FxTable", "extends RefCounted",
             "## AUTO-GENERATED by tools/generate_pixel_art.py. Maps fighter id + move key to pixel-art effects,",
             "## so roster scripts stay untouched. Edit the generator (or this table) to retarget art.", "", "const FX := {"]
    for fid in sorted(table):
        lines.append('\t"%s": {' % fid)
        for mv in ("basic", "special1", "special2", "ultimate"):
            if mv in table[fid]:
                lines.append('\t\t"%s": %s,' % (mv, table[fid][mv]))
        lines.append("\t},")
    lines += ["}", "", "static func apply(fighter_id: String, moves: Dictionary) -> void:",
              "\tvar t: Dictionary = FX.get(fighter_id, {})",
              "\tfor key in t:",
              "\t\tif moves.has(key):",
              "\t\t\tfor k in t[key]:",
              "\t\t\t\tmoves[key][k] = t[key][k]", ""]
    open(os.path.join(ROOT, "fx_table.gd"), "w").write("\n".join(lines))
    print("wrote sheets, %d melee fx, %d projectile strips, traps, icons, arena" % (len(MELEE), len(PROJ)))

if __name__ == "__main__":
    main()
